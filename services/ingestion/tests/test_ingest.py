import json
from pathlib import Path

import httpx
import pytest
import respx
from sqlalchemy import func, select
from tenacity import wait_none

from common.models import Movie
from ingestion.ingest import discover_ids, fetch_and_store, upsert_movies
from ingestion.mapper import details_to_row
from ingestion.tmdb_client import BASE_URL, TmdbClient

INTERSTELLAR = json.loads(
    (Path(__file__).parent / "fixtures" / "interstellar_details.json").read_text(encoding="utf-8")
)

pytestmark = pytest.mark.anyio


@pytest.fixture
def anyio_backend() -> str:
    return "asyncio"


def fake_details(tmdb_id: int) -> dict:
    return INTERSTELLAR | {"id": tmdb_id, "title": f"Movie {tmdb_id}"}


def test_upsert_twice_keeps_one_row_and_refreshes_it(db_session) -> None:
    row = details_to_row(INTERSTELLAR)
    upsert_movies(db_session, [row])
    first_updated_at = db_session.scalar(select(Movie.updated_at))

    upsert_movies(db_session, [row | {"vote_count": 40000}])

    movie = db_session.scalars(select(Movie)).one()  # still one row
    assert movie.vote_count == 40000
    # now() is the transaction start time, so each upsert (own transaction) moves it.
    assert movie.updated_at > first_updated_at
    assert "interstellar" in movie.title_search  # generated by Postgres


@respx.mock
async def test_discover_ids_dedupes_and_still_reaches_the_limit() -> None:
    pages = {
        1: [{"id": i} for i in range(1, 21)],
        2: [{"id": 20}] + [{"id": i} for i in range(21, 40)],  # 20 moved down a page
        3: [{"id": i} for i in range(40, 60)],
    }
    respx.get(f"{BASE_URL}/discover/movie").mock(
        side_effect=lambda request: httpx.Response(
            200, json={"results": pages.get(int(request.url.params["page"]), [])}
        )
    )

    async with TmdbClient("t", wait=wait_none()) as tmdb:
        # 40 = exactly two pages. The duplicate on page 2 leaves 39 unique ids there, so
        # without the spare page this would return 39.
        ids = await discover_ids(tmdb, limit=40)

    assert ids == list(range(1, 41))


@respx.mock
async def test_fetch_and_store_counts_missing_and_failed_movies(db_session) -> None:
    def details(request: httpx.Request) -> httpx.Response:
        tmdb_id = int(request.url.path.rsplit("/", 1)[1])
        if tmdb_id == 404:
            return httpx.Response(404)
        if tmdb_id == 500:
            return httpx.Response(500)
        return httpx.Response(200, json=fake_details(tmdb_id))

    respx.get(url__regex=rf"{BASE_URL}/movie/\d+").mock(side_effect=details)
    ids = [*range(1, 151), 404, 500]  # 150 good ones: more than one upsert batch

    async with TmdbClient("t", wait=wait_none()) as tmdb:
        report = await fetch_and_store(tmdb, db_session, ids)

    assert (report.upserted, report.not_found, report.failed) == (150, 1, 1)
    assert db_session.scalar(select(func.count()).select_from(Movie)) == 150
