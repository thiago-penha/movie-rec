"""Fetch movies from TMDB and upsert them into `movies`."""

import asyncio
import logging
import math
from collections.abc import Iterable
from dataclasses import dataclass
from typing import Any

from sqlalchemy import func
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.orm import Session

from common.config import get_settings
from common.models import Movie
from ingestion.mapper import details_to_row
from ingestion.tmdb_client import TmdbClient

logger = logging.getLogger(__name__)

# TMDB's /discover returns 20 movies per page and refuses pages above 500, so one
# sort order reaches at most 10,000 movies.
PAGE_SIZE = 20
MAX_DISCOVER_PAGES = 500
UPSERT_BATCH_SIZE = 100

# Columns the upsert overwrites on conflict: everything TMDB provides. Not `id` (ours),
# `created_at` (first insert), or `title_search` (generated by Postgres).
_UPDATABLE = [
    column.name
    for column in Movie.__table__.columns
    if column.name not in {"id", "created_at", "title_search", "updated_at"}
]


class MissingTokenError(RuntimeError):
    """TMDB_API_KEY is empty. A normal Exception, not SystemExit, so a worker job
    that hits it fails like any other job instead of killing the worker process."""


def tmdb_token() -> str:
    token = get_settings().tmdb_api_key
    if token is None or not token.get_secret_value():
        raise MissingTokenError("TMDB_API_KEY is not set. Put your TMDB v4 read token in .env.")
    return token.get_secret_value()


def upsert_movies(session: Session, rows: list[dict[str, Any]]) -> None:
    """Insert new movies and update existing ones, matched on tmdb_id.

    INSERT ... ON CONFLICT DO UPDATE is one atomic statement, so running the seed twice
    (or two workers ingesting the same movie) never creates duplicates.
    """
    if not rows:
        return
    statement = insert(Movie).values(rows)
    # `excluded` is Postgres' name for the row we tried to insert.
    statement = statement.on_conflict_do_update(
        index_elements=[Movie.tmdb_id],
        set_={name: statement.excluded[name] for name in _UPDATABLE} | {"updated_at": func.now()},
    )
    session.execute(statement)
    session.commit()


async def discover_ids(tmdb: TmdbClient, limit: int) -> list[int]:
    """TMDB ids of the `limit` most voted movies, most voted first."""
    # Rankings shift while the pages are fetched (movies with equal vote counts have no
    # fixed order, and votes change), so a movie can appear on two pages. Duplicates are
    # dropped below; one spare page makes up for them.
    pages = min(math.ceil(limit / PAGE_SIZE) + 1, MAX_DISCOVER_PAGES)
    if limit >= MAX_DISCOVER_PAGES * PAGE_SIZE:
        # shortcut: one sort order caps at 10k ids, and duplicates make the real number
        # slightly lower (9996 in the first full seed). Split /discover by year ranges
        # if the catalog ever needs more.
        logger.warning("TMDB discover caps at %d movies", MAX_DISCOVER_PAGES * PAGE_SIZE)
    # gather keeps the results in page order, even though the requests run concurrently.
    # Pages past the last one come back with an empty list, so no need to check
    # total_pages first.
    results = await asyncio.gather(*(tmdb.discover_page(page) for page in range(1, pages + 1)))
    ids = [movie["id"] for result in results for movie in result["results"]]
    return list(dict.fromkeys(ids))[:limit]


@dataclass
class SeedReport:
    upserted: int = 0
    not_found: int = 0
    failed: int = 0


async def fetch_and_store(tmdb: TmdbClient, session: Session, ids: Iterable[int]) -> SeedReport:
    """Fetch details for `ids` concurrently and upsert them in batches.

    One failed movie is logged and counted; it does not stop the others.
    """
    report = SeedReport()

    async def fetch(tmdb_id: int) -> tuple[int, dict[str, Any] | None | BaseException]:
        try:
            return tmdb_id, await tmdb.movie_details(tmdb_id)
        except Exception as error:  # after retries; keep going with the other movies
            return tmdb_id, error

    batch: list[dict[str, Any]] = []
    # All tasks start at once, but the client's semaphore lets only 10 requests out at
    # a time. as_completed hands back each result as soon as it arrives.
    for next_done in asyncio.as_completed([fetch(tmdb_id) for tmdb_id in ids]):
        tmdb_id, result = await next_done
        if isinstance(result, BaseException):
            report.failed += 1
            logger.error("tmdb_id=%s failed: %r", tmdb_id, result)
        elif result is None:
            report.not_found += 1
            logger.warning("tmdb_id=%s not found on TMDB", tmdb_id)
        else:
            batch.append(details_to_row(result))
        if len(batch) >= UPSERT_BATCH_SIZE:
            # A sync DB call inside async code blocks the event loop for a few ms per
            # 100 rows. Requests already in flight keep going; that is fine for a CLI.
            upsert_movies(session, batch)
            report.upserted += len(batch)
            batch = []
            logger.info("upserted %d movies", report.upserted)
    upsert_movies(session, batch)
    report.upserted += len(batch)
    return report


async def seed(session: Session, limit: int) -> SeedReport:
    async with TmdbClient(tmdb_token()) as tmdb:
        ids = await discover_ids(tmdb, limit)
        logger.info("discovered %d movies, fetching details", len(ids))
        return await fetch_and_store(tmdb, session, ids)


async def ingest_movie(session: Session, tmdb_id: int) -> None:
    """Fetch and upsert one movie (the `ingest_movie` job). Raises if it cannot."""
    async with TmdbClient(tmdb_token()) as tmdb:
        details = await tmdb.movie_details(tmdb_id)
    if details is None:
        raise LookupError(f"tmdb_id={tmdb_id} not found on TMDB")
    upsert_movies(session, [details_to_row(details)])
